/**
 * 剧本参考（Scenario Brief）—— 人工策展的 1931 历史剧情设定。
 *
 * 目的：给各 AI 注入"历史应该大致怎么走"的锚点，让 AI 行为有历史依据，
 * 而非仅靠 LLM 自身资料库。这是"剧本"层，与种子数据（世界态）分离。
 *
 * 用法：
 * - buildScenarioBrief()：全局时代背景 + 各方处境 + 关键节点 + 叙事基调
 * - buildFactionBrief(faction)：分势力历史剧本（角色扮演锚点）
 *
 * 注意：剧本是"叙事导向"，不是硬性剧情——AI 仍按当前世界态自由决策，
 * 剧本只是帮助它贴合历史处境与意图。
 */
import { Owner, OWNER_LABELS } from './owners'

const GLOBAL_BRIEF = `【剧本参考 · 1931 年 4 月】
时代背景：九一八事变爆发在即。中原大战方歇，国民政府名义统一，实则军阀割据、宁粤分裂。日本关东军盘踞南满，虎视眈眈；东北军张学良拥兵关外，却受命"攘外必先安内"。国共内战正酣，红军在江西苏区抗击第三次围剿。

各方意图：
- 国民政府(KMT)：名义正统，控制华东华中华南。内削异己、外御日本，先内后外，重点剿共与收编地方势力。
- 中共苏区(CCP)：江西红色政权，装备简陋士气高昂，在围剿中图存，伺机扩大苏区。
- 日本关东军(JPN)：盘踞南满（大连/旅顺/南满铁路），精锐骄横，蓄谋寻衅——九一八是它的历史窗口。
- 东北军(NEA)：张学良拥兵关外，受制于人、优柔寡断，面对关东军进退失据。
- 晋系/桂系/川军/马家军/新疆/西藏/滇系/黔系：各自割据，名义归附，观望中央与日本博弈。

关键节点（叙事导向，非硬性剧情）：
- 1931-09 九一八：关东军寻衅南满，东北军不抵抗，东北速失。
- 1931-12 宁粤和解、蒋介石一度下野。
- 1932 一二八淞沪抗战、伪满洲国成立。

叙事基调：半文言、野心昭然、地缘博弈。各势力以自身利益为先，不轻言仁义。`

export function buildScenarioBrief(): string {
  return GLOBAL_BRIEF
}

const FACTION_BRIEF: Record<string, string> = {
  [Owner.KMT]: '历史走向：攘外必先安内——先剿共、收编地方军阀，再对日。对日避战为主，防内部分裂。',
  [Owner.CCP]: '历史走向：在围剿中图存，伺机扩大苏区、打运动战，避免硬拼。',
  [Owner.JPN]:
    '历史走向：1931-09 九一八是你的历史窗口——趁东北军不抵抗，寻衅南满、集中精锐速占东北要地。兵力稀缺，须集中打击、以小博大。',
  [Owner.NEA]: '历史走向：面对关东军，倾向观望退让、不急于开战，受令留驻关内而举棋不定。',
  [Owner.SHX]: '历史走向：中原大战新败，守成为主，北防日军、东防中央，不轻易出兵。',
  [Owner.GXC]: '历史走向：偏安西南，伺机再起，以小搏大。',
  [Owner.SCC]: '历史走向：先整合川内派系，再图中原。',
  [Owner.MA]: '历史走向：先固西北根本，再谋扩张。',
  [Owner.XJ]: '历史走向：以稳内为主，警惕苏联边界渗透。',
  [Owner.TIB]: '历史走向：凭险自守，东防川军、南防英印，闭关自守。',
  [Owner.YUN]: '历史走向：先固边疆，再图出滇。',
  [Owner.GUI]: '历史走向：依附强邻苟存，或趁中央势力未至扩张。',
}

export function buildFactionBrief(faction: Owner): string {
  const label = OWNER_LABELS[faction] ?? faction
  const brief = FACTION_BRIEF[faction]
  if (!brief) return ''
  return `【势力剧本 · ${label}】\n${brief}`
}